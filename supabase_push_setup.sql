-- Weekwise background Web Push
-- Run in Supabase SQL Editor before deploying the weekwise-push Edge Function.
-- Browser clients never receive direct access to subscription/delivery records.
-- The service-role key stays inside the Supabase Edge Function runtime.

create table if not exists public.weekwise_push_subscriptions (
  endpoint text primary key check (endpoint like 'https://%'),
  user_id uuid not null references auth.users(id) on delete cascade,
  subscription jsonb not null check (jsonb_typeof(subscription) = 'object'),
  timezone text not null default 'UTC',
  user_agent text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists weekwise_push_subscriptions_user_id_idx
  on public.weekwise_push_subscriptions (user_id);

alter table public.weekwise_push_subscriptions enable row level security;
revoke all on table public.weekwise_push_subscriptions from public, anon, authenticated;
grant all on table public.weekwise_push_subscriptions to service_role;

create table if not exists public.weekwise_push_delivery_log (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  task_id text not null,
  reminder_at text not null,
  status text not null check (status in ('processing', 'sent', 'failed')),
  attempt_count integer not null default 1 check (attempt_count > 0),
  attempted_at timestamptz not null default now(),
  sent_at timestamptz,
  last_error text,
  created_at timestamptz not null default now(),
  unique (user_id, task_id, reminder_at)
);

create index if not exists weekwise_push_delivery_log_user_recent_idx
  on public.weekwise_push_delivery_log (user_id, attempted_at desc);

alter table public.weekwise_push_delivery_log enable row level security;
revoke all on table public.weekwise_push_delivery_log from public, anon, authenticated;
grant all on table public.weekwise_push_delivery_log to service_role;

create or replace function public.weekwise_claim_push_delivery(
  p_user_id uuid,
  p_task_id text,
  p_reminder_at text
)
returns boolean
language plpgsql
security definer
set search_path = pg_catalog, public, auth
as $function$
declare
  claimed_id bigint;
begin
  if coalesce(auth.role(), '') <> 'service_role' then
    raise exception 'Only the trusted Weekwise push dispatcher may claim deliveries.'
      using errcode = '42501';
  end if;

  if p_user_id is null or coalesce(btrim(p_task_id), '') = '' or coalesce(btrim(p_reminder_at), '') = '' then
    raise exception 'User, task and reminder identifiers are required.'
      using errcode = '22023';
  end if;

  insert into public.weekwise_push_delivery_log
    (user_id, task_id, reminder_at, status, attempt_count, attempted_at)
  values
    (p_user_id, p_task_id, p_reminder_at, 'processing', 1, now())
  on conflict (user_id, task_id, reminder_at) do update
    set status = 'processing',
        attempt_count = public.weekwise_push_delivery_log.attempt_count + 1,
        attempted_at = now(),
        last_error = null
    where public.weekwise_push_delivery_log.status <> 'sent'
      and public.weekwise_push_delivery_log.attempted_at < now() - interval '5 minutes'
  returning id into claimed_id;

  return claimed_id is not null;
end;
$function$;

revoke all on function public.weekwise_claim_push_delivery(uuid, text, text) from public, anon, authenticated;
grant execute on function public.weekwise_claim_push_delivery(uuid, text, text) to service_role;
